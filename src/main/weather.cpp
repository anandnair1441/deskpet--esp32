    c.toUpperCase();
    String cityLine = c + "." + countryCode;
    display.print(cityLine);

    if      (weatherIcon == "01d") display.drawBitmap(93, 12, bmp_clear_day,         32, 32, SSD1306_WHITE);
    else if (weatherIcon == "01n") display.drawBitmap(93, 12, bmp_clear_night,       32, 32, SSD1306_WHITE);
